#!/usr/bin/env python3
"""Generate softclip.inc, the output table of the mixer in sbmix.asm.

The mixer adds up to eight channels; the sum (-512..511 after scaling) is
turned into one unsigned 8-bit sample through this table.  Up to +-KNEE the
table is linear (a single sample keeps its level), above that it approaches
+-127 smoothly instead of clipping hard."""
import math

KNEE, TOP = 88, 127


def f(x):
    a = abs(x)
    y = a if a <= KNEE else KNEE + (TOP - KNEE) * (1 - math.exp(-(a - KNEE) / (TOP - KNEE)))
    y = min(TOP, round(y))
    return y if x >= 0 else -y


vals = [128 + f(x) for x in range(-512, 512)]
with open("softclip.inc", "w") as o:
    o.write("; output byte for a mixed sample of -512..511 (generated by mktab.py)\n")
    for i in range(0, 1024, 16):
        o.write("        db " + ",".join(str(v) for v in vals[i:i + 16]) + "\n")
