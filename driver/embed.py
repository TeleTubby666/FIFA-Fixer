#!/usr/bin/env python3
"""Generated parts of the two patchers.

    python3 driver/embed.py          assemble CUST_DIG.ADV with nasm, update fifafixer.py,
                                     c/custdig.h and c/mixtab.h
    python3 driver/embed.py --check  only check that they are current

fifafixer.py carries the driver zlib-compressed and base64-encoded between the
DRIVER BEGIN / DRIVER END marker lines; c/custdig.h carries it as a byte array.
c/mixtab.h is the table MIXER_BUILDS of fifafixer.py for the C tool.
"""
import base64
import os
import subprocess
import sys
import tempfile
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PY = os.path.join(ROOT, "fifafixer.py")
HDR = os.path.join(ROOT, "c", "custdig.h")
TAB = os.path.join(ROOT, "c", "mixtab.h")
BEGIN = "# --- DRIVER BEGIN (generated by driver/embed.py, do not edit) ---"
END = "# --- DRIVER END ---"


def assemble():
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "CUST_DIG.ADV")
        subprocess.run(["nasm", "-f", "bin", "-o", out, "sbmix.asm"], cwd=HERE, check=True)
        with open(out, "rb") as fh:
            return fh.read()


def py_block(drv):
    b64 = base64.b64encode(zlib.compress(drv, 9)).decode("ascii")
    lines = [BEGIN, "DRIVER_SIZE = %d" % len(drv), "DRIVER_CRC32 = 0x%08X" % (zlib.crc32(drv) & 0xFFFFFFFF),
             "DRIVER_Z = ("]
    lines += ['    "%s"' % b64[i:i + 96] for i in range(0, len(b64), 96)]
    lines += [")", END]
    return "\n".join(lines)


def c_header(drv):
    out = ["/* CUST_DIG.ADV, the mixer driver (driver/sbmix.asm).",
           "   Generated by driver/embed.py, do not edit. */",
           "#define DRIVER_SIZE %uu" % len(drv),
           "#define DRIVER_CRC32 0x%08XUL" % (zlib.crc32(drv) & 0xFFFFFFFF),
           "static const unsigned char DRIVER[DRIVER_SIZE] = {"]
    for i in range(0, len(drv), 16):
        out.append("    " + ",".join("0x%02X" % b for b in drv[i:i + 16]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def mixer_table():
    sys.path.insert(0, ROOT)
    import fifafixer
    out = ["/* The mixer regions, MIXER_BUILDS of fifafixer.py.",
           "   Generated by driver/embed.py, do not edit. */"]
    entries = []
    for size in sorted(fifafixer.MIXER_BUILDS):
        for k, (off, c, d) in enumerate(fifafixer.MIXER_BUILDS[size]):
            c, d = bytes.fromhex(c), bytes.fromhex(d)
            for name, data in (("o", c), ("d", d)):
                out.append("static const unsigned char MX_%d_%d_%s[%d] = {" % (size, k, name, len(data)))
                for i in range(0, len(data), 16):
                    out.append("    " + ",".join("0x%02X" % b for b in data[i:i + 16]) + ",")
                out.append("};")
            entries.append("    { %dUL, 0x%04XUL, %du, MX_%d_%d_o, MX_%d_%d_d }," % (size, off, len(c), size, k, size, k))
    out.append("static const MixRegion MIX_REGIONS[] = {")
    out += entries
    out.append("};")
    out.append("#define N_MIX_REGIONS %du" % len(entries))
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    drv = assemble()
    with open(PY, encoding="utf-8") as fh:
        py = fh.read()
    a, b = py.index(BEGIN), py.index(END) + len(END)
    new_py = py[:a] + py_block(drv) + py[b:]
    new_h = c_header(drv)
    old_h = open(HDR, encoding="ascii").read() if os.path.exists(HDR) else ""
    new_t = mixer_table()
    old_t = open(TAB, encoding="ascii").read() if os.path.exists(TAB) else ""
    if check:
        ok = new_py == py and new_h == old_h and new_t == old_t
        print("driver embedding is %s" % ("current" if ok else "OUT OF DATE (run driver/embed.py)"))
        return 0 if ok else 1
    with open(PY, "w", encoding="utf-8") as fh:
        fh.write(new_py)
    with open(HDR, "w", encoding="ascii") as fh:
        fh.write(new_h)
    with open(TAB, "w", encoding="ascii") as fh:
        fh.write(new_t)
    print("CUST_DIG.ADV: %d bytes, CRC-32 %08X" % (len(drv), zlib.crc32(drv) & 0xFFFFFFFF))
    return 0


if __name__ == "__main__":
    sys.exit(main())
